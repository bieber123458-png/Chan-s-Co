// 限動組成效：完成率＝最後一則瀏覽÷第一則瀏覽；互動率＝互動÷第一則瀏覽
export function storyMetrics(s, followers) {
  const first = Number(s.firstViews) || 0;
  const last = Number(s.lastViews) || 0;
  const inter = (Number(s.interactions) || 0) + (Number(s.replies) || 0);
  return {
    completion: first && s.lastViews !== '' && s.lastViews != null ? Math.round((last / first) * 100) : null,
    engagement: first ? Math.round((inter / first) * 1000) / 10 : null,
    reachRate: first && followers ? Math.round((first / followers) * 1000) / 10 : null,
  };
}
