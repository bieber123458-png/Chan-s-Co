// 依頁數與風格產生逐頁結構
export function buildCarousel(pages, styleKey) {
  const n = Math.min(10, Math.max(5, Number(pages) || 7));
  const style = CAROUSEL_STYLES[styleKey] || CAROUSEL_STYLES.teach;
  const out = [{ role: '封面', layout: '大字標題＋你的臉或成果圖', limit: 15, hint: '數字＋結果，或一個讓人停下來的問句' }];
  out.push({ role: '共鳴頁', layout: '一句話＋情境照片', limit: 40, hint: '為什麼要看下去：說出觀眾正在經歷的事' });
  const points = n - 4;
  for (let i = 0; i < points; i++) {
    out.push({ role: `重點 ${i + 1}`, layout: style.layouts[i % style.layouts.length], limit: 60, hint: '一頁只講一個重點：小標題＋2～3 行說明' });
  }
  out.push({ role: '總結頁', layout: '重點清單一頁看完', limit: 60, hint: '讓人想收藏的整理頁' });
  out.push({ role: '行動頁', layout: '頭像＋一句行動呼籲', limit: 30, hint: '收藏、分享、留言關鍵字或追蹤，只選一個' });
  return out.map((p, i) => ({ ...p, no: i + 1, total: n, title: '', text: '' }));
}

